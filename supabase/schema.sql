-- Accounts and deck sync.
--
-- Paste into the Supabase SQL editor and run once. Re-running is safe: every
-- statement is IF NOT EXISTS, CREATE OR REPLACE, or a DROP paired with a
-- CREATE, so applying it twice changes nothing.
--
-- The shape follows data/decks.db rather than inventing a new one — `decks` is
-- `lists` with an owner, `deck_cards` is `list_cards` unchanged. What is added
-- is only what starts mattering once there is more than one person and more
-- than one device: who owns a row, which copy is newer, and what a deletion
-- means.
--
-- Read the row-level security section at the bottom before changing anything.
-- The API here is generated from these tables and the key that reaches it ships
-- inside the page's JavaScript, on purpose. Those policies are not a hardening
-- pass on top of the security — they are the security.


-- ---------------------------------------------------------------------------
-- profiles — the public half of an account
-- ---------------------------------------------------------------------------
-- auth.users cannot be made readable: it holds email addresses, and there is no
-- policy that exposes a display name without exposing those too. A published
-- deck still has to say who built it, so the shareable half of an account lives
-- here, and this is the only table a byline ever joins against.
create table if not exists public.profiles (
    id         uuid primary key references auth.users(id) on delete cascade,
    username   text not null unique,
    created_at timestamptz not null default now()
);

-- A row here for every signup, without the client having to remember to make
-- one. The placeholder name is deliberately ugly so that "pick a username"
-- reads as unfinished rather than as a name somebody chose.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.profiles (id, username)
    values (new.id, 'player-' || substr(replace(new.id::text, '-', ''), 1, 8))
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();


-- ---------------------------------------------------------------------------
-- decks — data/decks.db's `lists`, with an owner
-- ---------------------------------------------------------------------------
create table if not exists public.decks (
    -- A uuid rather than the local integer id, and generated by the client
    -- before the first push. Sync then has one key that means the same deck on
    -- every device, and pushing twice is an upsert instead of a duplicate. The
    -- default is only a safety net for rows made by hand in the dashboard.
    id             uuid primary key default gen_random_uuid(),
    user_id        uuid not null references auth.users(id) on delete cascade,

    -- Straight across from `lists`.
    name           text not null,
    kind           text not null default 'list' check (kind in ('list', 'deck')),
    commander_id   text,
    partner_id     text,
    notes          text,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),

    -- A tombstone, not a real delete.
    --
    -- Sync cannot tell "deleted on the laptop" from "not created on the laptop
    -- yet" by absence alone, so a hard delete on one device comes back from the
    -- other on the next pull. Marking the row and keeping it is what makes a
    -- deletion something that can travel. Everything below filters on it.
    deleted_at     timestamptz,

    -- Publishing. Unused until the community browse page exists, but the
    -- columns are here now because adding them later is a migration against
    -- live user data, and adding them now is free.
    --
    -- The summary fields are denormalised at publish time on purpose: the
    -- browse page can then sort and filter without the server knowing anything
    -- about Magic, and the 29 MB card database never has to exist up here.
    -- Card art comes from Scryfall's CDN, which serves it CORS-open.
    is_public      boolean not null default false,
    published_at   timestamptz,
    commander_name text,
    color_identity text,
    card_count     integer not null default 0
);

-- The local database enforces one name per list, case-insensitively. The same
-- rule, scoped per person — your "Goblins" must not collide with anyone else's,
-- and a deleted deck must not reserve its name forever.
create unique index if not exists decks_user_name_idx
    on public.decks (user_id, lower(name))
    where deleted_at is null;

create index if not exists decks_user_idx
    on public.decks (user_id)
    where deleted_at is null;

-- What the browse page will page through.
create index if not exists decks_public_idx
    on public.decks (published_at desc)
    where is_public and deleted_at is null;


-- ---------------------------------------------------------------------------
-- deck_cards — data/decks.db's `list_cards`, unchanged
-- ---------------------------------------------------------------------------
-- card_id is a Scryfall id and stays text. Nothing up here validates it against
-- a card pool, because nothing up here has one.
create table if not exists public.deck_cards (
    deck_id  uuid    not null references public.decks(id) on delete cascade,
    card_id  text    not null,
    qty      integer not null default 1 check (qty > 0),
    label    text,
    added_at timestamptz not null default now(),
    primary key (deck_id, card_id)
);


-- ---------------------------------------------------------------------------
-- Row-level security
-- ---------------------------------------------------------------------------
-- This is the whole permission model. With RLS off, these tables are readable
-- and writable by anyone who views source and copies the key — which is the
-- single most common way a Supabase project gets wrecked. Leave it on.
alter table public.profiles   enable row level security;
alter table public.decks      enable row level security;
alter table public.deck_cards enable row level security;

-- profiles: legible to everyone, editable only by their owner. Public read is
-- required for bylines on published decks and exposes nothing but a username.
drop policy if exists profiles_read      on public.profiles;
drop policy if exists profiles_write_own on public.profiles;
drop policy if exists profiles_edit_own  on public.profiles;

create policy profiles_read on public.profiles
    for select using (true);
create policy profiles_write_own on public.profiles
    for insert with check (id = auth.uid());
create policy profiles_edit_own on public.profiles
    for update using (id = auth.uid()) with check (id = auth.uid());

-- decks: yours are yours; a published deck is readable by anybody, signed in or
-- not. Note the read policy deliberately still shows you your own tombstoned
-- rows — sync has to see a deletion to replay it — while the public half hides
-- them.
drop policy if exists decks_read   on public.decks;
drop policy if exists decks_insert on public.decks;
drop policy if exists decks_update on public.decks;
drop policy if exists decks_delete on public.decks;

create policy decks_read on public.decks
    for select using (
        user_id = auth.uid()
        or (is_public and deleted_at is null)
    );
create policy decks_insert on public.decks
    for insert with check (user_id = auth.uid());
create policy decks_update on public.decks
    for update using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy decks_delete on public.decks
    for delete using (user_id = auth.uid());

-- deck_cards: no opinion of its own, it inherits whatever the parent deck
-- allows. Writing is stricter than reading — a published deck is readable by
-- everyone but editable only by its owner, so the two subqueries differ.
drop policy if exists deck_cards_read  on public.deck_cards;
drop policy if exists deck_cards_write on public.deck_cards;

create policy deck_cards_read on public.deck_cards
    for select using (
        exists (
            select 1 from public.decks d
            where d.id = deck_id
              and (d.user_id = auth.uid() or (d.is_public and d.deleted_at is null))
        )
    );
create policy deck_cards_write on public.deck_cards
    for all using (
        exists (
            select 1 from public.decks d
            where d.id = deck_id and d.user_id = auth.uid()
        )
    ) with check (
        exists (
            select 1 from public.decks d
            where d.id = deck_id and d.user_id = auth.uid()
        )
    );
